// Regenerates lib/palette-defaults.ts and app/palette.css from Tailwind's own default palette.
// Run with:  node scripts/gen-palette.mjs   (only needed if you add a palette to USED or upgrade Tailwind)
import { readFileSync, writeFileSync } from "node:fs";

const USED = ["stone", "slate", "emerald", "teal", "amber", "rose", "sky", "orange", "lime", "red"];
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const css = readFileSync("node_modules/tailwindcss/theme.css", "utf8");

const palettes = {};
for (const name of USED) {
  palettes[name] = SHADES.map((s) => {
    const m = css.match(new RegExp(`--color-${name}-${s}:\\s*([^;]+);`));
    if (!m) throw new Error(`missing --color-${name}-${s}`);
    return m[1].trim();
  });
}

writeFileSync(
  "lib/palette-defaults.ts",
  `// GENERATED by scripts/gen-palette.mjs from Tailwind's default theme. Do not edit by hand.\n` +
    `export const SHADES = ${JSON.stringify(SHADES)} as const;\n` +
    `export const DEFAULT_PALETTES: Record<string, string[]> = ${JSON.stringify(palettes, null, 2)};\n`,
);

let out = `/* GENERATED by scripts/gen-palette.mjs. Do not edit by hand.
 *
 * Every palette colour the app uses is routed through a runtime variable (--c-<palette>-<shade>)
 * with Tailwind's default as the fallback. With no theme applied nothing changes; a theme just sets
 * the --c-* variables on <html> (see lib/theme.ts). Going through var() also stops Tailwind from
 * inlining colours at build time, so opacity variants like bg-emerald-50/70 follow the theme too.
 */
@theme {
`;
for (const [name, vals] of Object.entries(palettes))
  SHADES.forEach((s, i) => (out += `  --color-${name}-${s}: var(--c-${name}-${s}, ${vals[i]});\n`));
out += `  --color-white: var(--c-white, #fff);\n}\n`;
writeFileSync("app/palette.css", out);
console.log("palettes:", Object.keys(palettes).join(", "));
